def init_m2_registry():
    registry = {}
    dependencies = {}

    for spec in M2_ROLES_SPEC:
        agent_id = spec["id"]
        dependencies[agent_id] = spec["deps"]
        registry[agent_id] = {
            "agent_id": agent_id,
            "division": spec["div"],
            "specialty": spec["specialty"],
            "assigned_task": spec["task"],
            "dependency_ids": spec["deps"],
            "worktree_or_workspace": f"m2_workspace_{spec['div'].lower()}",
            "owned_files": spec["files"],
            "execution_state": "PENDING" if spec["deps"] else "READY",
            "is_instantiated": False,
            "produced_artifacts": [],
            "tests_executed": [],
            "test_outcomes": {},
            "commit_sha": None,
            "integration_status": "PENDING",
            "blocking_issues": [],
            "evidence_references": []
        }

    with open(REGISTRY_PATH, "w", encoding="utf-8") as f:
        json.dump(registry, f, indent=2)

    with open(DEPENDENCIES_PATH, "w", encoding="utf-8") as f:
        json.dump(dependencies, f, indent=2)

    # Initialize empty execution events
    if not EVENTS_PATH.exists():
        with open(EVENTS_PATH, "w", encoding="utf-8") as f:
            f.write(json.dumps({"event": "INIT_M2_CONTROL_PLANE", "total_roles": len(registry)}) + "\n")

    print(f"Initialized M2 Swarm Control Plane with {len(registry)} specialist roles.")

if __name__ == "__main__":
    init_m2_registry()
