def init_registry():
    registry = {}
    dependencies = {}
    
    for spec in ROLES_SPEC:
        agent_id = spec["id"]
        dependencies[agent_id] = spec["deps"]
        registry[agent_id] = {
            "agent_id": agent_id,
            "division": spec["div"],
            "division_name": DIVISIONS[spec["div"]][0],
            "specialty": spec["specialty"],
            "assigned_task": spec["task"],
            "dependency_ids": spec["deps"],
            "worktree_or_workspace": f"workspace_{spec['div'].lower()}",
            "owned_files": spec["files"],
            "execution_state": "PENDING" if spec["deps"] else "READY",
            "produced_artifacts": [],
            "tests_executed": [],
            "test_outcomes": {},
            "commit_sha": None,
            "integration_status": "PENDING",
            "blocking_issues": [],
            "evidence_references": []
        }

    with open(REGISTRY_PATH, "w", encoding="utf-8") as f:
        json.dump(registry, f, indent=2)

    with open(DEPENDENCIES_PATH, "w", encoding="utf-8") as f:
        json.dump(dependencies, f, indent=2)

    print(f"Initialized registry with {len(registry)} specialist roles across {len(DIVISIONS)} divisions.")

if __name__ == "__main__":
    init_registry()
